ACC = {'\u00c1': 'A', '\u00c9': 'E', '\u00cd': 'I', '\u00d3': 'O', '\u00da': 'U',
       '\u00d1': 'N', '\u00dc': 'U'}


def glyph(ch):
    ch = ch.upper()
    if ch in ACC:
        ch = ACC[ch]
    return G.get(ch, G[' ']).split('/')


def text_alpha(s, scale=1, tracking=1, space_rows=0):
    """Devuelve array (H,W) 0/1 con el texto renderizado."""
    gs = [glyph(c) for c in s]
    wch = 5 + tracking
    W = max(1, len(s) * wch - tracking)
    H = 7
    img = np.zeros((H + space_rows, W), float)
    x = 0
    for i, g in enumerate(gs):
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == '#':
                    img[space_rows + r, x + c] = 1.0
        x += wch
    if scale != 1:
        img = np.repeat(np.repeat(img, scale, 0), scale, 1)
    return img


def text_size(s, scale=1, tracking=1):
    return (7 * scale, max(1, (len(s) * (5 + tracking) - tracking)) * scale)
